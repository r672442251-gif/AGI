// @api report which service blocks this node carries and on which ports
import { NextResponse } from "next/server"

import { listServices } from "@/lib/microservices/registry"

// СОСТАВ УЗЛА НАРУЖУ — ОДНА ДВЕРЬ, ЧИТАЮЩАЯ ОДИН РЕЕСТР (264-1).
//
// 🔒 ЗАЧЕМ ОНА НУЖНА, ЕСЛИ РЕЕСТР МОЖНО ПРОЧИТАТЬ СЕРВЕРНЫМ КОМПОНЕНТОМ. Страницы
// слоя архитектора ПРЕДРЕНДЕРЕНЫ. Порт, прочитанный на сборке, запекается в HTML
// и остаётся там навсегда: в день, когда установщик уступил номер и назначил
// другой, страница продолжит уверенно печатать старый. Это ровно тот класс, за
// который проект уже платил, — «прибор, печатающий запомненное значение, врёт
// именно тогда, когда на него полагаются». Поэтому число спрашивают в браузере, а
// не запекают.
//
// 🔒 `force-dynamic` ЗДЕСЬ ЗАКОНЕН И ОБЯЗАТЕЛЕН — это маршрут данных, а не
// страница публичного слоя. Застывший ответ о составе узла есть та же запечённая
// ложь, только этажом ниже.
//
// 🔒 ДВЕРЬ ЗАКРЫТА ВОРОТАМИ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. Её имени НЕТ в
// `PUBLIC_API_PREFIXES` (`proxy.ts`) намеренно: закон о сменных блоках говорит
// «ничего своего наружу — узнавший наши порты и схемы привязан к нам». Состав
// узла — сведение о машине человека, а не о продукте. Проходят те же, кто и к
// прочим дверям: хозяин за клавиатурой этой машины, временный адрес и сессия.
//
// 🛑 СЕКРЕТОВ ЗДЕСЬ НЕ БЫВАЕТ, И ЭТО СВОЙСТВО ИСТОЧНИКА, А НЕ ЭТОГО ФАЙЛА.
// `AGI-ITEMS-REGISTRY/agi-items.json` лежит в git и уезжает каждому гостю; ключи живут в `.env`
// службы, которого реестр не видит. Дверь ничего к файлу не добавляет — она его
// отдаёт. Если однажды в реестре появится секрет, чинить надо реестр.
export const dynamic = "force-dynamic"

export function GET() {
  const services = listServices().map((s) => ({
    id: s.id,
    port: s.port,
    version: s.version,
    provides: s.provides,
    required: s.required ?? false,
    // 🔒 «УСТАНОВЛЕНА» — ЭТО ПРО НАЗНАЧЕННЫЙ ПОРТ, А НЕ ПРО ЖИВОСТЬ ПРОЦЕССА.
    // Живость знает только опрос по сети, и он стоит денег на каждый запрос
    // страницы. Два состояния названы разными словами намеренно: «не установлена»
    // — это адрес, куда идти, «не отвечает» — это отказ, и путать их дорого.
    installed: typeof s.port === "number",
  }))

  // 🔒 `count` ПОРОЖДАЕТСЯ, А НЕ ПИШЕТСЯ. Рукописное число расходится со списком
  // молча — закон проекта, оплаченный трижды подряд одним и тем же автором.
  return NextResponse.json({ ok: true, count: services.length, services })
}
