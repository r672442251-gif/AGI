import { PostBody } from '@/components/content-page/post-body'
import { PageHeader } from '@/components/content-page/page-header.server'
import { PageShell } from '@/components/content-page/page-shell'
import { Breadcrumbs } from '@/components/nav/breadcrumbs.server'
import type { ReactNode } from 'react'
import type { Block, WorkspaceItem } from '@/lib/content/blocks/types'
import { architectLayerUi } from '../_i18n/architect-layer.i18n'
import { architectMenu, ARCHITECT_HOME } from './architect-menu'
import { withDrafts } from './draft-menu'
import { OwnerBand } from '../_components/owner-band.client'

// ОБОЛОЧКА СТРАНИЦЫ СЛОЯ АРХИТЕКТОРА (236-2).
//
// 🔒 ОДНА ОБОЛОЧКА НА ДЕСЯТЬ СТРАНИЦ — ПО ТОЙ ЖЕ ПРИЧИНЕ, ПО КОТОРОЙ МЕНЮ ЖИВЁТ
// В ОДНОМ МЕСТЕ. Десять страниц, каждая со своим куском разметки, разойдутся на
// первой же правке вида: у девяти появится новое поле, у десятой нет. Страница
// слоя обязана уметь сказать ровно две вещи — свой адрес и своё имя,
// — а всё остальное берётся отсюда.
//
// 🔒 РИСУЕТ `PostBody` — ТОТ ЖЕ, ЧТО РИСУЕТ СТАТЬЮ. Это и есть исполнение закона
// «одно ядро, а не набор частей»: слой архитектора не получает второй системы
// разметки, он получает те же виды каталога под замком. ✗ Именно здесь служба
// памяти ушла в сторону — её экран мастерской собран собственными клиентскими
// островками, и рядом с каталогом видов появилась вторая вёрстка.
//
// 🔒 НИ ОДНОГО ЧТЕНИЯ СЕССИИ, `cookies()` ИЛИ `headers()`. Страница остаётся
// статической; кого пускать, решает замок слоя, а данные отдают двери `/api/*`.

export function ArchitectPage({
  lang,
  path,
  title,
  children = [],
  lead,
  pageTitle,
  pageLead,
  tabs,
  widget,
}: {
  lang: string
  /** Адрес БЕЗ языка, ровно как в источнике меню: по нему отмечается активный пункт. */
  path: string
  /** Имя раздела — заголовок правой части, внутри рабочего экрана. */
  title: string
  /** Содержимое раздела. Пусто — страница показывает своё устройство, и это законно. */
  children?: Block[]
  lead?: string
  /**
   * Заголовок САМОЙ СТРАНИЦЫ — над рабочим экраном, слева, с бейджем слоя.
   * Решение владельца 2026-09-19: «Это надпись самой страницы, она должна
   * находиться сверху блока workspace… в левом верхнем углу вместе с бейджем в
   * едином стиле». Не задан — шапки нет вовсе, и это законно: у раздела своё имя
   * уже стоит внутри рабочего экрана.
   */
  pageTitle?: string
  pageLead?: string
  /**
   * Верхний ряд — НАВИГАЦИЯ ПО ЭТОЙ ЖЕ СТРАНИЦЕ: якоря с плавной прокруткой.
   *
   * 🔒 Решение владельца 2026-09-19, сначала о входе в слой («ты продублировал
   * это меню и слева, и сверху; это меню предназначено только для навигации по
   * странице с плавной прокруткой»), а затем, тем же вечером, обо всём слое:
   * разделы группы уехали в подменю левого меню.
   *
   * 🛑 НЕ ЗАДАН — РЯДА НЕТ ВОВСЕ, и это законное состояние страницы, у которой
   * ещё нет собственных тем. Прежнее умолчание (собрать ряд из разделов группы)
   * отменено вместе с `architectTabs`.
   */
  tabs?: WorkspaceItem[]
  /** Собственный островок маршрута (271) — рисуется в рабочем экране над блоками. */
  widget?: ReactNode
}) {
  const ui = architectLayerUi(lang)

  const blocks: Block[] = [
    {
      kind: 'workspace',
      menuTitle: ui.menuTitle,
      menu: withDrafts(architectMenu(lang, path), lang, path),
      tabs,
      title,
      // 🔒 «РАЗДЕЛ НА МЕСТЕ, СОДЕРЖИМОЕ ПРИДЁТ» ГОВОРИТСЯ ТОЛЬКО ПУСТОМУ РАЗДЕЛУ.
      // ✗ найдено глазами 2026-09-19: у входа в слой содержимое уже есть, а эта
      // строка всё равно стояла под заголовком и обещала, что страницы ещё нет.
      // Уверенное умолчание дороже отсутствующего: человек читает его как факт.
      lead: lead ?? (children.length > 0 || widget ? undefined : ui.emptyLead),
      children,
      widget,
    },
  ]

  // 🔒 КРОШКИ СОБИРАЮТСЯ ЗДЕСЬ, А ГАСИТ ИХ PLATFORM CONFIG — решение владельца
  // 2026-09-19: «все страницы, кроме корня, смотрят в platform config, чтобы
  // понять, какие атрибуты они должны возвращать: хлебные крошки, секцию
  // вопрос-ответ и так далее».
  //
  // 🔒 ВЫКЛЮЧАТЕЛЬ ПРОВЕРЯЕТ НЕ ЭТОТ ФАЙЛ, А `PageHeader`: он и рисует крошки, и
  // ставит для поисковика разметку `BreadcrumbList`. Гейт у ОДНОГО потребителя, а
  // не у двух — иначе выключенные крошки исчезли бы с экрана и остались в
  // разметке, то есть мы пообещали бы машине то, чего человек не видит.
  //
  // 🔒 КРОШКИ ЕСТЬ НА КАЖДОЙ СТРАНИЦЕ, КРОМЕ ГЛАВНОЙ — решение владельца
  // 2026-09-19: «для любых других страниц хлебные крошки мы всегда обязательно
  // активируем по умолчанию, чтобы они всегда присутствовали, разумеется кроме
  // главной страницы».
  //
  // 🪦 ОТМЕНЕНО МОЁ ПРЕЖНЕЕ РЕШЕНИЕ: вход в слой я оставлял без крошек, рассудив,
  // что «у корня раздела нет уровня выше». Довод неверен: уровень выше есть
  // всегда — сам сайт. Крошка на входе в слой читается как «Fractera → Архитектор»
  // и говорит человеку, где он находится, а не куда ему идти.
  //
  // 🛑 ГЛАВНАЯ — ЕДИНСТВЕННОЕ ИСКЛЮЧЕНИЕ, и оно не про настройку: на корне сайта
  // крошка указывала бы на саму себя.
  //
  // Последний элемент идёт БЕЗ адреса: это текущая страница, и ссылка на неё была
  // бы ссылкой в никуда.
  // 🔒 КРОШКА НАЗЫВАЕТ СТРАНИЦУ, А НЕ ОТКРЫТЫЙ ВНУТРИ НЕЁ РАЗДЕЛ (253). У страницы
  // группы это разные слова: сверху стоит «Строительство», а внутри рабочего
  // экрана — «Обзор». Крошка «Fractera → Архитектор → Обзор» назвала бы человеку
  // место, которого в меню не существует.
  const breadcrumbs =
    path === ARCHITECT_HOME
      ? [{ label: ui.layer }]
      : [
          { href: `/${lang}${ARCHITECT_HOME}`, label: ui.layer },
          { label: pageTitle ?? title },
        ]

  return (
    <PageShell top="work" className="flex flex-col gap-6">
      <OwnerBand
        title={ui.authWarning.title}
        reasonMachine={ui.authWarning.reasonMachine}
        reasonTemporary={ui.authWarning.reasonTemporary}
        reasonShowcase={ui.authWarning.reasonShowcase}
        body={ui.authWarning.body}
        titleMachine={ui.authWarning.titleMachine}
        bodyMachine={ui.authWarning.bodyMachine}
      />

      {/* 🔒 ШАПКА СТРАНИЦЫ — НАД РАБОЧИМ ЭКРАНОМ, СЛЕВА (решение владельца
          2026-09-19: «это надпись самой страницы, она должна находиться сверху
          блока workspace… в левом верхнем углу вместе с бейджем в едином стиле»).

          🛑 РАНЬШЕ ЭТОТ ТЕКСТ ЖИЛ ВНУТРИ РАБОЧЕГО ЭКРАНА и рисовался как `H3`
          правой колонки. Снаружи он читался как заголовок РАЗДЕЛА, а не страницы,
          и `H1` у страницы не было вовсе — дефект и для человека, и для поисковика
          сразу.

          ✗ ПЕРВАЯ РЕДАКЦИЯ СОБИРАЛА ШАПКУ РУКАМИ — своим тегом шапки, заголовком
          первого уровня и подзаголовком, — и сторож типографики назвал это по
          имени: «шапка страницы собрана вручную, мимо PageHeader». Он прав: у
          продукта ОДИН примитив шапки, и вторая её сборка разошлась бы с первой
          на первой же правке ритма. `eyebrow` здесь и есть тот самый бейдж.

          🛑 И ВТОРОЙ УРОК, ОПЛАЧЕННЫЙ ТУТ ЖЕ: первая версия этого объяснения
          процитировала удалённый тег ДОСЛОВНО — и сторож засчитал цитату за живой
          код, оставшись красным после починки. Надгробие пишется ПЕРЕСКАЗОМ;
          закон известен и был нарушен через минуту после того, как я его вспомнил. */}
      {pageTitle ? (
        <PageHeader
          lang={lang}
          eyebrow={ui.layer}
          title={pageTitle}
          subtitle={pageLead}
          breadcrumbs={breadcrumbs}
        />
      ) : (
        breadcrumbs && <Breadcrumbs lang={lang} trail={breadcrumbs} />
      )}

      <PostBody blocks={blocks} lang={lang} />
    </PageShell>
  )
}
